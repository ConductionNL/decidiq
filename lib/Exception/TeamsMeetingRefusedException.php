declare(strict_types=1);

namespace OCA\Decidiq\Exception;

/**
 * A refused Teams meeting action and its HTTP status.
 *
 * @spec openspec/changes/platform-microsoft-365-calendar-and-teams/specs/microsoft-365-work/spec.md#requirement-req-m365-004-a-digital-or-hybrid-meeting-can-carry-a-teams-meeting
 */
class TeamsMeetingRefusedException extends \RuntimeException {
	/**
	 * Constructor.
	 *
	 * @param string $message The reason, shown to the clerk
	 * @param int    $status  The HTTP status to answer
	 *
	 * @return void
	 */
	public function __construct(string $message, private readonly int $status=409) {
		parent::__construct(message: $message);
	}//end __construct()

	/**
	 * The HTTP status to answer.
	 *
	 * @return int The status.
	 *
	 * @spec openspec/changes/platform-microsoft-365-calendar-and-teams/specs/microsoft-365-work/spec.md#requirement-req-m365-004-a-digital-or-hybrid-meeting-can-carry-a-teams-meeting
	 */
	public function getStatus(): int {
		return $this->status;
	}//end getStatus()
}//end class
